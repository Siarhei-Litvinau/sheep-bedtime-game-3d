import * as THREE from 'three';

/**
 * Освещение сцены (раздел 7): направленные источники (солнце + луна)
 * + мягкий fill-свет (hemisphere). Без PBR, без динамических теней —
 * flat/toon-friendly схема, дешёвая на мобильных.
 *
 * Настройки цвета/интенсивности здесь — стартовые для базовой сцены;
 * управление кривой день→ночь (раздел 6) подключится позже через update().
 *
 * Оба источника закреплены за сценой целиком (мировые координаты),
 * а не за текущей сфокусированной овцой — камера-ревизия, раздел 3:
 * свет не должен "следовать" за объектом или казаться светящим ему
 * в спину. Угол подобран как боковой/three-quarter (не анфас, не
 * строго сверху), чтобы объекты отбрасывали читаемую боковую тень.
 */
export function createLighting(scene) {
  const sun = new THREE.DirectionalLight(0xffd9a8, 1.2);
  sun.position.set(-14, 16, 6); // над тёплой (светлой, x<0) половиной планеты — раздел 1 ревизии: день слева
  sun.target.position.set(0, 0, 0);
  scene.add(sun);
  scene.add(sun.target);

  // "Луна" — боковой свет тёмной половины (x>0). Без неё амбар/забор/овца
  // на ночной стороне подсвечивались только тёплым sun-светом сквозь всю
  // сцену (DirectionalLight не ограничен полусферой) — раздел 3 ревизии
  // явно требует на тёмной стороне отдельный приглушённый холодный боковой
  // свет, а не тёплый спилловер с дневной. Цвет — приглушённый серо-синий,
  // не насыщенный синий (по тексту ревизии).
  const moon = new THREE.DirectionalLight(0x8a97b8, 0.4);
  moon.position.set(14, 13, 5); // зеркально солнцу по X — над тёмной половиной
  moon.target.position.set(0, 0, 0);
  scene.add(moon);
  scene.add(moon.target);

  const fill = new THREE.HemisphereLight(0x8fa8c9, 0x2a2230, 0.55);
  scene.add(fill);

  return { sun, moon, fill };
}
